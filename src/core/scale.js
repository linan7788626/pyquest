// ============================================================
// 世界比例常量：角色/物件相对逻辑瓦片（16px）的显示倍率
// - CS = 2：所有「角色」（勇者/长老/史莱姆/BOSS/巨蟒）显示为基准的 2 倍
// - PS = 2.5：环境物件（树/石碑/火把/符文石…）跟随放大，保持世界观协调
// 调整这里即可整体缩放，无需改动各场景调用点
// ============================================================
export const CS = 2;   // 角色倍率：16px 基准 → 32px
export const PS = 2.5; // 物件倍率：16px 基准 → 40px

/** 角色贴图逻辑基准 16px 时的显示尺寸 */
export const charSize = (n = 16) => n * CS;
